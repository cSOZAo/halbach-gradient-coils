    @staticmethod
    def _roi_cylinder_collision(rx: float, ry: float, rz: float,
                                r_inner: float, half_h: float) -> list:
        """Return human-readable reasons why the ROI is outside the bore.

        The ROI must lie inside the hollow bore (radius ``r_inner``,
        |z| <= ``half_h``). An axis-aligned ellipsoid centered at the origin
        fits iff max(Rx, Ry) <= R_int and Rz <= H/2.
        """
        reasons = []
        rho_max = max(rx, ry)
        if rho_max > r_inner + 1e-12:
            reasons.append(
                f"ROI radial (max Rx/Ry={rho_max*1000:.1f} mm) > "
                f"R_int={r_inner*1000:.1f} mm")
        if rz > half_h + 1e-12:
            reasons.append(
                f"ROI axial (Rz={rz*1000:.1f} mm) > "
                f"H/2={half_h*1000:.1f} mm")
        return reasons

    def _redraw_geo3d_preview(self):
        """3D hollow cylinder (R_int / R_ext / height) + ROI ellipsoid (Rx, Ry, Rz).

        Physical frame: bore along +Z, ROI along X/Y/Z = Rx/Ry/Rz.
        Display remap plots (X, Z, Y) so matplotlib's vertical axis is Y.
        """
        try:
            cfg = self._preview_cfg()
        except ValueError:
            self._geo3d_show_message(self.root.tr("Invalid input"))
            return

        r_outer = cfg.shell_outer_radius
        r_inner = cfg.shell_inner_radius
        height = cfg.cylinder.height
        rx, ry, rz = cfg.target.rx, cfg.target.ry, cfg.target.rz

        if (r_outer <= 0 or r_inner <= 0 or r_inner >= r_outer
                or height <= 0 or rx <= 0 or ry <= 0 or rz <= 0):
            self._geo3d_show_message(self.root.tr("Invalid geometry"))
            return

        ax = self.geo3d_ax
        ax.clear()

        half_h = 0.5 * height
        collision = self._roi_cylinder_collision(rx, ry, rz, r_inner, half_h)
        # Plot in mm so axis ticks match the GUI units.
        scale = 1000.0
        r_outer_mm = r_outer * scale
        r_inner_mm = r_inner * scale
        half_h_mm = half_h * scale
        rx_mm, ry_mm, rz_mm = rx * scale, ry * scale, rz * scale

        n_th = 48
        n_z = 12
        theta = np.linspace(0.0, 2.0 * math.pi, n_th)
        zs = np.linspace(-half_h_mm, half_h_mm, n_z)
        Theta, Z = np.meshgrid(theta, zs)

        # Outer / inner cylindrical walls (physical axis along +Z).
        # Display as (X, Z, Y) so Y is the vertical screen axis.
        Xo = r_outer_mm * np.cos(Theta)
        Yo = r_outer_mm * np.sin(Theta)
        Xi = r_inner_mm * np.cos(Theta)
        Yi = r_inner_mm * np.sin(Theta)
        ax.plot_surface(Xo, Z, Yo, color='#9aa3ad', alpha=0.28,
                        linewidth=0, antialiased=True, shade=True)
        ax.plot_surface(Xi, Z, Yi, color='#c5cdd6', alpha=0.22,
                        linewidth=0, antialiased=True, shade=True)

        # Annular end caps at physical z = ±height/2.
        rr = np.linspace(r_inner_mm, r_outer_mm, 8)
        Theta_c, R_c = np.meshgrid(theta, rr)
        Xc = R_c * np.cos(Theta_c)
        Yc = R_c * np.sin(Theta_c)
        for z_cap in (-half_h_mm, half_h_mm):
            ax.plot_surface(Xc, np.full_like(Xc, z_cap), Yc,
                            color='#7a8490', alpha=0.35, linewidth=0,
                            antialiased=True, shade=True)

        # Outline rings to clarify the bore.
        th = np.linspace(0.0, 2.0 * math.pi, 80)
        for r in (r_inner_mm, r_outer_mm):
            x_ring = r * np.cos(th)
            y_ring = r * np.sin(th)
            for z_ring in (-half_h_mm, half_h_mm):
                ax.plot(x_ring, np.full_like(th, z_ring), y_ring,
                        color='#333333', lw=0.9, alpha=0.85)

        # ROI ellipsoid: blue if inside bore, red if colliding / outside.
        u = np.linspace(0.0, 2.0 * math.pi, 36)
        v = np.linspace(0.0, math.pi, 20)
        xe = rx_mm * np.outer(np.cos(u), np.sin(v))
        ye = ry_mm * np.outer(np.sin(u), np.sin(v))
        ze = rz_mm * np.outer(np.ones_like(u), np.cos(v))
        roi_color = '#e53935' if collision else '#2f80ed'
        ax.plot_surface(xe, ze, ye, color=roi_color, alpha=0.50,
                        linewidth=0, antialiased=True, shade=True)

        lim = max(half_h_mm, r_outer_mm, rx_mm, ry_mm, rz_mm) * 1.15
        self._set_axes_equal_3d(ax, lim)
        ax.set_xlabel('X [mm]', fontsize=7, labelpad=-2)
        ax.set_ylabel('Z [mm]', fontsize=7, labelpad=-2)
        ax.set_zlabel('Y [mm]', fontsize=7, labelpad=-2)
        ax.tick_params(labelsize=6, pad=-2)
        ax.view_init(elev=18, azim=-60)

        title = (
            f"Rint={r_inner*1000:.1f}  Rext={r_outer*1000:.1f}  H={height*1000:.0f} mm\n"
            f"ROI  Rx={rx*1000:.1f}  Ry={ry*1000:.1f}  Rz={rz*1000:.1f} mm"
        )
        if collision:
            title += "\n⚠ " + self.root.tr("ROI outside / colliding with shell")
            ax.set_title(title, fontsize=7.5, pad=4, color='#b71c1c')
            if hasattr(self, 'geo3d_alert_lbl'):
                self.geo3d_alert_lbl.config(
                    text=self.root.tr("Alert: {details}", details="; ".join(collision)),
                    foreground='#b71c1c')
        else:
            ax.set_title(title, fontsize=7.5, pad=4, color='#222222')
            if hasattr(self, 'geo3d_alert_lbl'):
                self.geo3d_alert_lbl.config(
                    text=self.root.tr("ROI inside bore (no collision)"),
                    foreground='#2e7d32')
        self.geo3d_mpl_canvas.draw_idle()

    @staticmethod
    def _annular_sector_poly(r_in: float, r_out: float,
                             t0: float, t1: float, n: int = 72) -> np.ndarray:
        """Closed polygon for an annular sector (angles in radians, CCW from +x)."""
        ts_out = np.linspace(t0, t1, n)
        ts_in = np.linspace(t1, t0, n)
        x = np.concatenate([r_out * np.cos(ts_out), r_in * np.cos(ts_in)])
        y = np.concatenate([r_out * np.sin(ts_out), r_in * np.sin(ts_in)])
        return np.column_stack([x, y])

    @staticmethod
    def _radial_ellipse_polys(
        center_radius: float,
        theta: float,
        semi_radial: float,
        semi_tangent: float,
        peel_toward: str,
        peel_frac: float,
        n: int = 48,
    ) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Return (kept, peel, outline) polygons for a radially aligned groove ellipse.

        ``peel_toward`` is ``'out'`` (toward +radial / R_ext) or ``'in'``
        (toward -radial / R_int). ``peel_frac`` is ``auto_margin_pct`` in [0, 1].
        """
        peel_frac = float(np.clip(peel_frac, 0.0, 1.0))
        rux, ruy = math.cos(theta), math.sin(theta)
        tux, tuy = -math.sin(theta), math.cos(theta)
        gx = center_radius * rux
        gy = center_radius * ruy

        def _xy(lr: float, lt: float) -> Tuple[float, float]:
            return (gx + lr * rux + lt * tux, gy + lr * ruy + lt * tuy)

        def _on_ellipse(a: float) -> Tuple[float, float]:
            return _xy(semi_radial * math.cos(a), semi_tangent * math.sin(a))

        outline = np.asarray(
            [_on_ellipse(2.0 * math.pi * i / n) for i in range(n)], dtype=float)

        # Peel depth along local radial from the free-surface tip.
        peel = 2.0 * peel_frac * semi_radial
        if peel < 1e-15 or semi_radial <= 0:
            return outline.copy(), np.empty((0, 2)), outline

        if peel_toward == 'out':
            # Peel occupies lr in (split, +semi]; split = semi - peel.
            split = semi_radial - peel
            split = float(np.clip(split, -semi_radial, semi_radial))
            a0 = math.acos(float(np.clip(split / semi_radial, -1.0, 1.0)))
            # Outer tip: a in [-a0, +a0] (cos large / outward).
            peel_poly = np.asarray(
                [_on_ellipse(a) for a in np.linspace(-a0, a0, max(n // 2, 8))],
                dtype=float)
            # Kept: complementary arc a in [a0, 2pi - a0].
            kept_poly = np.asarray(
                [_on_ellipse(a) for a in np.linspace(a0, 2.0 * math.pi - a0,
                                                     max(n, 16))],
                dtype=float)
        else:
            # Peel occupies lr in [-semi, split); split = -semi + peel.
            split = -semi_radial + peel
            split = float(np.clip(split, -semi_radial, semi_radial))
            a0 = math.acos(float(np.clip(split / semi_radial, -1.0, 1.0)))
            # Inner tip: a in [a0, 2pi - a0] (cos small / inward).
            peel_poly = np.asarray(
                [_on_ellipse(a) for a in np.linspace(a0, 2.0 * math.pi - a0,
                                                     max(n // 2, 8))],
                dtype=float)
            # Kept: complementary outer-ish arc a in [-a0, +a0].
            kept_poly = np.asarray(
                [_on_ellipse(a) for a in np.linspace(-a0, a0, max(n, 16))],
                dtype=float)

        return kept_poly, peel_poly, outline


class _AspectFrame(ttk.Frame):
    """Container that keeps a child at a fixed width/height ratio while
    centering it inside whatever space the layout gives it.

    Prevents Matplotlib canvases from stretching into unreadable ovals when
    the window is resized.
    """

    def __init__(self, master, aspect: float = 1.0, **kw):
        super().__init__(master, **kw)
        self.aspect = float(aspect)  # width / height
        self.inner = ttk.Frame(self)
        self.inner.place(relx=0.5, rely=0.5, anchor='center')
        self.bind('<Configure>', self._on_configure)

    def _on_configure(self, event):
        w, h = event.width, event.height
        if w < 2 or h < 2 or self.aspect <= 0:
            return
        if (w / h) > self.aspect:
            nh = h
            nw = max(1, int(round(h * self.aspect)))
        else:
            nw = w
            nh = max(1, int(round(w / self.aspect)))
        self.inner.place_configure(width=nw, height=nh)


